import { problems } from "../learning";
import type { TeachingLesson, TeachingTransfer } from "../teaching";

const math = String.raw;
const originalProblems = new Map(problems.map((problem) => [problem.id, problem]));
const entries: Record<string, TeachingLesson> = {};

type Choice = [label: string, feedback: string];

function example(
  prompt: string,
  promptFormula: string,
  answer: number,
  solution: string,
  remediation: string,
): TeachingTransfer {
  return {
    prompt,
    promptFormula,
    answer,
    solution,
    remediation,
    signFeedback: "结果的大小对了。再检查它应该带的符号。" + remediation,
  };
}

function teach(
  id: string,
  strategy: string,
  target: string,
  plain: string,
  prompt: string,
  correct: Choice,
  misconception: Choice,
  prerequisite: string,
  transfer: TeachingTransfer,
) {
  const problem = originalProblems.get(id);
  if (!problem || !("solution" in problem) || !problem.guidedHints?.length || entries[id]) {
    throw new Error("Invalid chapter-one lesson source: " + id);
  }
  const hints = problem.guidedHints.filter((hint) => !hint.formula.includes("?"));
  const setup = hints[0];
  const working = setup ? hints : problem.guidedHints;
  const correctIndex = Object.keys(entries).length % 2;
  const choices = correctIndex === 0 ? [correct, misconception] : [misconception, correct];
  const steps: TeachingLesson["steps"] = [
    {
      id: id + "-idea",
      goal: target,
      plain,
      formula: setup?.formula ?? problem.formula,
      detail: setup ? correct[1] + setup.text : correct[1],
      check: {
        prompt,
        choices: choices.map(([label]) => label),
        correct: correctIndex,
        feedback: choices.map(([, feedback]) => feedback),
        prerequisite,
      },
    },
    ...working.slice(1).map((hint, index) => ({
      id: id + "-work-" + (index + 1),
      goal: hint.change,
      plain: hint.text,
      formula: hint.formula,
      detail: problem.explanation,
    })),
  ];
  steps.push({
    id: id + "-transfer",
    goal: "把这一步用到一题新题",
    plain: "先用刚才的办法处理新式子，再输入要求的数值。",
    formula: problem.solution,
    detail: problem.explanation,
    transfer,
  });
  entries[id] = {
    strategy,
    target,
    prerequisites: [prerequisite],
    solution: problem.solution,
    steps,
  };
}

