function lesson(
  id: string,
  strategy: keyof typeof prerequisites,
  goal: string,
  plain: string,
  solution: string,
  detail: string,
  understanding: TeachingCheck,
  practice: TeachingTransfer,
  referenceAnswer?: number,
  work = solution,
): TeachingLesson {
  const offset = Number(id.match(/\d+$/)?.[0] ?? 0) % understanding.choices.length;
  const rotate = (options: string[]) => [...options.slice(offset), ...options.slice(0, offset)];
  const understandingCheck = {
    ...understanding,
    choices: rotate(understanding.choices),
    feedback: rotate(understanding.feedback),
    correct: (understanding.correct + understanding.choices.length - offset) % understanding.choices.length,
  };

  return {
    target: goal,
    prerequisites: prerequisites[strategy],
    strategy,
    solution,
    referenceAnswer,
    steps: [
      { id: id + "-method", goal, plain, formula: work, detail, check: understandingCheck },
      {
        id: id + "-transfer",
        goal: "换一道题，自己走一遍",
        plain: "写下决定解法的那一步，再用迁移题给定的数据算出结果。",
        formula: practice.solution ?? "",
        detail: practice.remediation,
        transfer: practice,
      },
    ],
  };
}

