import type { TeachingCheck, TeachingLesson, TeachingTransfer } from "../teaching";

const math = String.raw;

type Option = [choice: string, feedback: string];

function check(prompt: string, right: Option, firstMistake: Option, secondMistake: Option, prerequisite: string): TeachingCheck {
  return {
    prompt,
    choices: [firstMistake[0], right[0], secondMistake[0]],
    correct: 1,
    feedback: [firstMistake[1], right[1], secondMistake[1]],
    prerequisite,
  };
}

function transfer(prompt: string, promptFormula: string, answer: number, solution: string, remediation: string): TeachingTransfer {
  const signFeedback = answer === 0
    ? "核对各项是否恰好抵消，或者其中是否带有零因子。"
    : "把每项的内层导数也乘进去，再核对最后相加或相减的符号。";
  return { prompt: prompt + " 若答案为无理数，请将小数保留到六位。", promptFormula, answer, solution, remediation, signFeedback };
}

function slope(formula: string, point: string, answer: number, solution: string, remediation: string): TeachingTransfer {
  return transfer(
    "先求导，再求所给点的导数值。可填小数或分数。",
    math`\begin{gathered}f(x)=${formula}\\ f'(${point})=?\end{gathered}`,
    answer,
    solution,
    remediation,
  );
}

