import type {
  TeachingCheck,
  TeachingLesson,
  TeachingStep,
  TeachingTransfer,
} from "../teaching";

interface ChoiceCheckInput {
  prompt: string;
  choices: string[];
  answer: string;
  feedback: Record<string, string>;
  prerequisite: string;
}

const toTeachingCheck = (input: ChoiceCheckInput): TeachingCheck => ({
  prompt: input.prompt,
  choices: input.choices,
  correct: input.choices.indexOf(input.answer),
  feedback: input.choices.map((choice) => input.feedback[choice] ?? ""),
  prerequisite: input.prerequisite,
});

const step = (
  id: string,
  goal: string,
  plain: string,
  formula: string,
  detail: string,
  check: ChoiceCheckInput,
  transfer?: TeachingTransfer,
): TeachingStep => ({
  id,
  goal,
  plain,
  formula,
  detail,
  check: toTeachingCheck(check),
  transfer,
});

